async function main() {
    console.log("Начинаем наполнение каталога услуг mit3...");

    for (const cat of catalog) {
        const { services, ...categoryData } = cat;

        const createdCategory = await prisma.serviceCategory.upsert({
            where: { slug: categoryData.slug },
            update: categoryData,
            create: categoryData,
        });

        for (const srv of services) {
            await prisma.service.upsert({
                where: { slug: srv.slug },
                update: {
                    ...srv,
                    categoryId: createdCategory.id,
                },
                create: {
                    ...srv,
                    categoryId: createdCategory.id,
                },
            });
        }
    }

    console.log("Каталог из 11 направлений и 15 услуг успешно загружен!");
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    })
    .finally(async () => {
        await prisma.$disconnect();
    });
